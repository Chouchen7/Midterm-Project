# keeps case punctuation and each newline as its own token spaces and tabs are dropped
TOKEN_RE = re.compile(r"\n|\w+|[^\w\s]")
def tokenize(text):
    return TOKEN_RE.findall(text)

# Vocabulary from the TRAIN split only
