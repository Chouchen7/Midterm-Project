# cut to MAX_LEN, pad on the right, keep true lengths
def encode(text):
    ids = [stoi.get(t, UNK) for t in tokenize(text)[:MAX_LEN]]
    n = max(len(ids), 1)
    ids += [PAD] * (MAX_LEN - len(ids))
    return ids, n

def build(split, column):
    d = data[data["split"] == split]
    enc = [encode(t) for t in d[column]]
